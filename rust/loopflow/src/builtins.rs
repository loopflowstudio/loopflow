//! Built-in skill definitions and system docs embedded in the binary.
//!
//! Registration is automatic: drop a file into the right builtins/
//! subdirectory and build.rs generates the HashMap entries.

use crate::definition::name::portable_name;

/// Launcher guidance shared by all agents; work APIs add the `work` skill body.
pub const LOOPFLOW_DOC: &str = include_str!("builtins/LOOPFLOW.md");

/// Headless preamble — the only surface that needs one (no user is present).
pub const SURFACE_HEADLESS: &str = include_str!("builtins/surfaces/headless.md");

/// Shared contract for every surface with someone participating in the current conversation.
pub const SURFACE_HUMAN_PRESENT: &str = include_str!("builtins/surfaces/human-present.md");

/// Live chat channel (e.g. Discord): a person is reading, so the reply is a
/// plain, deliberate, addressed message — never a working transcript.
pub const SURFACE_CHAT: &str = include_str!("builtins/surfaces/chat.md");

/// Returns the content of a built-in skill, if it exists.
pub fn get_builtin_skill(name: &str) -> Option<&'static str> {
    BUILTIN_SKILLS.get(portable_name(name).as_str()).copied()
}

/// One-line description for a built-in skill. Prefers the `description:` frontmatter
/// field, falling back to the first prose line after the closing `---`.
/// Returns an empty string if neither is present.
pub fn builtin_skill_description(name: &str) -> String {
    let Some(content) = get_builtin_skill(name) else {
        return String::new();
    };
    crate::skills::skill_description(content).unwrap_or_default()
}

/// Returns the content of a built-in graph, if it exists.
pub fn get_builtin_graph(name: &str) -> Option<&'static str> {
    BUILTIN_GRAPHS.get(portable_name(name).as_str()).copied()
}

/// Resolve a builtin skill key: exact name, `operate` for `repo-operate`, then
/// a unique namespace suffix. Returns `None` for absent or ambiguous names.
pub fn resolve_builtin_skill(name: &str) -> Option<&'static str> {
    if let Some((key, _)) = BUILTIN_SKILLS.get_key_value(portable_name(name).as_str()) {
        return Some(key);
    }
    // Repository operation owns the short name; Wave operation stays explicit.
    if name == "operate" {
        return BUILTIN_SKILLS
            .get_key_value("repo-operate")
            .map(|(key, _)| *key);
    }
    resolve_shortcut(name, BUILTIN_SKILLS_SHORTCUTS)
}

/// Resolve a canonical or slash spelling, then a unique source-namespace shortcut.
/// Hyphen suffixes do not create shortcuts. Absent or ambiguous names return `None`.
pub fn resolve_builtin_graph(name: &str) -> Option<&'static str> {
    if let Some((key, _)) = BUILTIN_GRAPHS.get_key_value(portable_name(name).as_str()) {
        return Some(key);
    }
    resolve_shortcut(name, BUILTIN_GRAPHS_SHORTCUTS)
}

fn resolve_shortcut(name: &str, shortcuts: &[(&str, &'static str)]) -> Option<&'static str> {
    shortcuts
        .iter()
        .find(|(bare, _)| *bare == name)
        .map(|(_, key)| *key)
}

/// List of all built-in skill names.
pub fn builtin_skill_names() -> Vec<&'static str> {
    BUILTIN_SKILLS.keys().copied().collect()
}

/// List of all built-in graph names.
pub fn builtin_graph_names() -> Vec<&'static str> {
    BUILTIN_GRAPHS.keys().copied().collect()
}

