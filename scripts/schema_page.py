#!/usr/bin/env python3
"""Write `rust/loopflow-storage/SCHEMA.md`: every table under its product concept.

    uv run python scripts/schema_page.py           # rewrite the page
    uv run python scripts/schema_page.py --check   # what CI runs

Tables come from replaying the migrations; concepts from the ownership map in
`docs/dev/reference.md`, which `check_architecture.py` keeps covering every
table. Members a migration marks `-- leaving:` show the Task that drops them;
`due_removals.py` prints when.

Stdlib only, like the migration check it builds on.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import check_migrations  # noqa: E402

REPO_ROOT = check_migrations.REPO_ROOT
PAGE = REPO_ROOT / "rust/loopflow-storage/SCHEMA.md"
REFERENCE = REPO_ROOT / "docs/dev/reference.md"
CONCEPT = re.compile(r"\*\*([^*]+)\*\*")
CODE = re.compile(r"`([^`]+)`")


def _concepts(tables: set[str]) -> list[tuple[str, list[str]]]:
    """Each ownership-map concept with the tables its Persistence cell names."""
    text = REFERENCE.read_text()
    section = text.split("<!-- architecture-map:start -->", 1)[1]
    section = section.split("<!-- architecture-map:end -->", 1)[0]
    rows = [line for line in section.splitlines() if line.startswith("| **")]
    headers = [cell.strip().casefold() for cell in section.splitlines()[1].strip("|").split("|")]
    persistence = headers.index("persistence")
    concepts = []
    for row in rows:
        cells = [cell.strip() for cell in row.strip().strip("|").split("|")]
        concept = CONCEPT.search(cells[0])
        named = [token for token in CODE.findall(cells[persistence]) if token in tables]
        if concept and named:
            concepts.append((concept.group(1), sorted(dict.fromkeys(named))))
    return concepts


def render() -> str:
    local = check_migrations._local_migrations()
    catalog = check_migrations.Catalog.of_origin_main(local)
    schema = check_migrations._schema(catalog.replay())
    leaving: dict[str, tuple[str, str]] = {}
    for name in catalog.ordered():
        for mark in check_migrations.leaving_marks(name, local[name].decode()):
            if schema.has(mark.member):
                leaving[mark.member] = (mark.task, Path(name).stem)

    def marked(member: str) -> str:
        task, migration = leaving[member]
        return f"leaving → {task}, {migration}"

    lines = [
        "# Store schema",
        "",
        "Generated by `uv run python scripts/schema_page.py` from the migrations and the",
        "ownership map in `docs/dev/reference.md`; do not edit. A leaving member names the",
        "Task that drops it and the migration that marked it. Never add a read or write",
        "to one. `uv run python scripts/due_removals.py` prints when each may drop.",
    ]
    placed: set[str] = set()
    concepts = _concepts(set(schema.tables))
    unmapped = sorted(set(schema.tables) - {t for _, tables in concepts for t in tables})
    if unmapped:
        concepts.append(("Not in the ownership map", unmapped))
    for concept, tables in concepts:
        lines += ["", f"## {concept}", ""]
        for table in tables:
            if table in placed:
                continue
            placed.add(table)
            columns = [
                f"~~{column}~~ ({marked(f'{table}.{column}')})"
                if f"{table}.{column}" in leaving
                else column
                for column in schema.tables[table]
            ]
            status = f" — **{marked(table)}**" if table in leaving else ""
            lines.append(f"- `{table}`{status}: {', '.join(columns)}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Write the generated store schema page.")
    parser.add_argument("--check", action="store_true", help="fail when the page is stale")
    args = parser.parse_args()
    page = render()
    if args.check:
        if not PAGE.exists() or PAGE.read_text() != page:
            print(
                f"{PAGE.relative_to(REPO_ROOT)} is stale; run uv run python scripts/schema_page.py",
                file=sys.stderr,
            )
            raise SystemExit(1)
        return
    PAGE.write_text(page)
    print(f"wrote {PAGE.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
